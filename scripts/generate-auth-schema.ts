/**
 * Regenerates src/server/db/auth-schema.ts from the installed Better Auth version.
 *
 * Better Auth 1.7 ships its Drizzle schema generator inside the adapter's
 * `relations-v2` entry. That generator also emits a relations block built on
 * `defineRelationsPart`, which exists only in Drizzle ORM 1.x. This app runs
 * Drizzle 0.45 and does not use relational queries for auth, so the script
 * keeps Better Auth's table definitions and drops that block.
 *
 * Usage: pnpm tsx scripts/generate-auth-schema.ts
 */
import { drizzleAdapter } from "@better-auth/drizzle-adapter/relations-v2";
import { mkdir, writeFile } from "node:fs/promises";
import { authSchemaOptions } from "../src/server/auth/options";

const dialect = process.argv[2] ?? "pg";
if (dialect !== "pg" && dialect !== "sqlite")
  throw new Error("Choose pg or sqlite.");
const target =
  dialect === "pg"
    ? "src/server/db/auth-schema.ts"
    : "src/server/db/sqlite/auth-schema.ts";
if (dialect === "sqlite")
  await mkdir("src/server/db/sqlite", { recursive: true });

const adapter = drizzleAdapter({}, { provider: dialect })(authSchemaOptions);
if (!adapter.createSchema)
  throw new Error("Installed Better Auth adapter has no schema generator.");

const generated = await adapter.createSchema(authSchemaOptions, target);
let code = generated.code;

const relationsStart = code.indexOf("export const authRelations");
if (relationsStart !== -1)
  code = code.slice(0, relationsStart).trimEnd() + "\n";
code = code.replace(/import \{\s*defineRelationsPart,?\s*/, "import { ");
code = code.replace(/import \{\s*\}\s*from "drizzle-orm";\n/, "");

const header = `// Generated by scripts/generate-auth-schema.ts from the installed Better Auth.
// Do not edit by hand; change src/server/auth/options.ts and regenerate.
`;

await writeFile(target, header + code);
console.log(`Wrote ${target}`);
