/**
 * Regenerates THIRD_PARTY_NOTICES.md from the installed production packages.
 *
 *   pnpm notices
 *
 * The list comes from `pnpm licenses list --prod --json`, so it always matches
 * the lockfile. Run it after changing dependencies.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

type Entry = { name: string; versions: string[]; license: string; homepage?: string; author?: string };

const raw = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
const byLicense = JSON.parse(raw) as Record<string, Entry[]>;
const entries = Object.values(byLicense)
  .flat()
  .sort((a, b) => a.name.localeCompare(b.name));

const NOTES: Record<string, string> = {
  "LGPL-3.0-or-later": "Shipped as an unmodified prebuilt library loaded at runtime by sharp (image resizing in Next.js). Its source is available from the libvips project.",
  "MPL-2.0": "Used unmodified. MPL-2.0 applies per file; any changes to these files would have to be shared under the same licence.",
  "CC-BY-4.0": "Browser support data used at build time. Attribution: the Can I Use project and its contributors.",
};

const lines = [
  "# Third-party notices",
  "",
  "Adapted Vercel AI Elements primitives in `src/components/assistant/internal/` retain Apache-2.0. See `third-party/ai-elements/NOTICE` for source pin and modifications, and `third-party/ai-elements/LICENSE` for the license. Streamdown also retains its Apache-2.0 license. Original Seller Desk code remains MIT.",
  "",
  "Interface components in `src/components/arc/` are vendored from Arc (https://github.com/kuratlielia/arc-library, commit 55c0d3ebd7cc643ec118c4d8a11413e6fadcc7df), MIT, Copyright (c) 2026 Elia Kuratli. Only import paths were changed; see `src/components/arc/README.md` and `src/components/arc/LICENSE`.",
  "",
  "The six demo product photos in `public/shop/` are AI-generated: made with OpenAI image generation (through Codex) from written prompts. They show fictional products for the demo shops.",
  "",
  "Seller Desk is MIT licensed (see LICENSE). It runs on the open-source packages below, each under its own licence.",
  "OpenRouter's Apache-2.0 adapter 3.1.0 is modified by the committed pnpm patch in `patches/`: its decision factory, method and text/JSON state handling follow the AI SDK 7.0.141 contract. The adapter retains Apache-2.0; these dependency modifications are not relabeled MIT.",
  `This list is generated by \`pnpm notices\` from the installed production dependencies (${entries.length} packages).`,
  "",
  "The local development installer also uses embedded-postgres 18.4.0-beta.17 and its platform package (MIT), from https://github.com/leinelissen/embedded-postgres. Its native PostgreSQL binaries have their own PostgreSQL licence: https://www.postgresql.org/about/licence/. These are downloaded as development dependencies, not included in the source archive or used as a hosted database.",
  "",
];
for (const [license, note] of Object.entries(NOTES)) {
  if (entries.some((entry) => entry.license === license)) lines.push(`**${license}:** ${note}`, "");
}
lines.push("| Package | Version | Licence | Home |", "| --- | --- | --- | --- |");
for (const entry of entries) {
  const home = entry.homepage ? entry.homepage.replace(/^git\+/, "").replace(/\.git$/, "") : "";
  lines.push(`| ${entry.name} | ${entry.versions.join(", ")} | ${entry.license} | ${home} |`);
}
writeFileSync("THIRD_PARTY_NOTICES.md", `${lines.join("\n")}\n`);
console.log(`THIRD_PARTY_NOTICES.md: ${entries.length} packages.`);
