/**
 * The fictional digital seller's sample pack: three original abstract
 * wallpapers (SVG, drawn by this code) and a short license, packed into a
 * store-only ZIP with fixed timestamps so the bytes are reproducible.
 */
const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = (CRC_TABLE[(crc ^ byte) & 0xff] as number) ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

/** Store-only ZIP (no compression). DOS time is fixed at 2026-01-01 00:00. */
export function buildZip(files: { name: string; content: string }[]): Buffer {
  const encoder = new TextEncoder();
  const dosTime = 0;
  const dosDate = ((2026 - 1980) << 9) | (1 << 5) | 1;
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  for (const file of files) {
    const name = Buffer.from(encoder.encode(file.name));
    const data = Buffer.from(encoder.encode(file.content));
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(0, 8);
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, name, data);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(dosTime, 12);
    central.writeUInt16LE(dosDate, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += local.length + name.length + data.length;
  }
  const centralSize = centrals.reduce((sum, part) => sum + part.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, ...centrals, end]);
}

/** One wallpaper from the sample pack (also used to draw the offer's preview image). */
export function wallpaper(hues: [number, number, number], seed: number): string {
  const rings = Array.from({ length: 7 }, (_, i) => {
    const r = 140 + i * 95 + ((seed * (i + 3)) % 40);
    const opacity = (0.5 - i * 0.06).toFixed(2);
    return `<circle cx="${1100 + ((seed * 37) % 300)}" cy="${300 + ((seed * 53) % 400)}" r="${r}" fill="none" stroke="hsl(${hues[2]} 70% 85%)" stroke-opacity="${opacity}" stroke-width="2"/>`;
  }).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1920 1080">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(${hues[0]} 55% 18%)"/><stop offset="1" stop-color="hsl(${hues[1]} 60% 42%)"/></linearGradient></defs>
<rect width="1920" height="1080" fill="url(#g)"/>${rings}
<text x="80" y="1000" font-family="Helvetica, Arial, sans-serif" font-size="28" fill="hsl(${hues[2]} 60% 92%)" fill-opacity="0.7">Northlight sample ${seed}</text>
</svg>
`;
}

export const SAMPLE_PACK_FILENAME = "northlight-sample-pack.zip";

export const SAMPLE_PACK_WALLPAPERS: { name: string; hues: [number, number, number]; seed: number }[] = [
  { name: "northlight-dawn.svg", hues: [215, 28, 40], seed: 1 },
  { name: "northlight-fjord.svg", hues: [195, 170, 160], seed: 2 },
  { name: "northlight-ember.svg", hues: [350, 20, 30], seed: 3 },
];

export function buildSamplePack(): Buffer {
  return buildZip([
    ...SAMPLE_PACK_WALLPAPERS.map((item) => ({ name: item.name, content: wallpaper(item.hues, item.seed) })),
    {
      name: "LICENSE.txt",
      content:
        "Northlight sample pack (fictional demo seller)\n\nThese three wallpapers were generated by the Seller Desk source code.\nYou may use, copy and modify them for any purpose, with no attribution required.\n",
    },
  ]);
}

